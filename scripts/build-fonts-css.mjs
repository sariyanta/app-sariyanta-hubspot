// Generates src/theme/sariyanta/styles/fonts.css with the font binaries inlined
// as base64 data: URIs. Inlining sidesteps HubSpot's get_asset_url (which emits
// an unreachable http://www.example.com/cmstp_projects/... URL for project
// theme assets, breaking fonts with CORS) and works identically on every portal
// and the real domain. Re-run only when the woff2 files change:
//   node scripts/build-fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const stylesDir = path.resolve(dir, '../src/theme/sariyanta/styles');

// Normal faces only — covers headings, body, and code. Italics are dropped to
// keep the inlined CSS lighter; browsers synthesize an acceptable oblique.
const faces = [
  { family: 'Newsreader', weight: '200 800', file: 'fonts/newsreader-normal.woff2' },
  { family: 'Inter', weight: '100 900', file: 'fonts/inter-normal.woff2' },
  { family: 'JetBrains Mono', weight: '100 800', file: 'fonts/jbmono-normal.woff2' },
];

const blocks = faces.map(({ family, weight, file }) => {
  const b64 = readFileSync(path.join(stylesDir, file)).toString('base64');
  return `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('data:font/woff2;base64,${b64}') format('woff2');
}`;
});

const header = `/* GENERATED by scripts/build-fonts-css.mjs — do not edit by hand.
   Font binaries (latin-subset variable woff2, normal weights) are inlined as
   base64 data: URIs so there is no external font URL for HubSpot to resolve —
   get_asset_url placeholder-domain and CORS issues all become irrelevant, and
   the fonts work on every portal and the real domain. Loaded via require_css from
   base.hubl.html. Tailwind --font-* vars that point at these families live in
   src/styles/theme.css. Re-run the generator when the woff2 files change. */`;

writeFileSync(path.join(stylesDir, 'fonts.css'), `${header}\n\n${blocks.join('\n\n')}\n`);
console.log(`Wrote ${path.join(stylesDir, 'fonts.css')} (${faces.length} faces)`);
